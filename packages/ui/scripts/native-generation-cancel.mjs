import { _electron as electron } from 'playwright-core';
import path from 'node:path';
import { cp, link, mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { modelFixture } from './native-model-fixture.mjs';

const repo = path.resolve(import.meta.dirname, '../../..');
const source = modelFixture(repo);
const root = await mkdtemp(path.join(repo, '.tmp/electron/generation-cancel-'));
const model = path.join(root, 'model');
await mkdir(model);
await cp(path.join(repo, '.tmp/electron/prototype-data/sessions'), path.join(root, 'sessions'), { recursive: true });
await writeFile(path.join(root, '.flow-recorder-development'), 'isolated generation cancellation\n');
for (const name of ['Qwen3-VL-2B-Instruct-Q8_0.gguf', 'mmproj-Qwen3-VL-2B-Instruct-Q8_0.gguf']) await link(path.join(source, name), path.join(model, name));
await cp(path.join(source, 'runtime.zip'), path.join(model, 'runtime.zip'));
const file = path.join(root, 'sessions', 'synthetic-settings', 'project.json');
const original = await readFile(file);
const packagedIndex = process.argv.indexOf('--packaged');
if (packagedIndex < 0) throw new Error('Use --packaged <exe>');
const executablePath = path.resolve(process.argv[packagedIndex + 1]);
const application = await electron.launch({ executablePath, cwd: path.dirname(executablePath), args: ['--data-root', root], timeout: 15_000 });
try {
  const page = await application.firstWindow();
  await page.getByRole('heading', { name: 'A calmer workspace' }).waitFor({ timeout: 15_000 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Verify existing files' }).click();
  await page.getByText(/Verified/).waitFor({ timeout: 30_000 });
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await page.locator('.library-list').getByRole('button').first().click();
  await page.getByRole('button', { name: /Notice the validation message/ }).click();
  await page.getByRole('button', { name: 'More actions' }).click();
  await page.getByRole('button', { name: 'Regenerate descriptions…' }).click();
  await page.getByRole('dialog', { name: 'Regenerate descriptions' }).getByRole('button', { name: 'Selected moment' }).click();
  const cancel = page.getByRole('button', { name: 'Cancel operation' });
  await cancel.waitFor({ timeout: 10_000 });
  await page.waitForTimeout(2_000);
  await cancel.click();
  await page.getByText('Operation cancelled · saved progress retained').waitFor({ timeout: 10_000 });
  if (!original.equals(await readFile(file))) throw new Error('Cancelling generation changed the saved project');
  console.log(JSON.stringify({ generation_cancellation: 'passed', root, project_unchanged: true }));
} finally { await application.close(); }
